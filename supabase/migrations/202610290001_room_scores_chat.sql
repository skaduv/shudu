-- Liquid Sudoku V1.1: collaborative scoreboard and room chat
-- Apply after 202610280001_online_rooms.sql.

alter table public.room_players
  add column if not exists score integer not null default 0,
  add column if not exists correct_moves integer not null default 0,
  add column if not exists mistakes integer not null default 0;

create table if not exists public.room_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 20),
  kind text not null default 'text' check (kind in ('text', 'emoji')),
  content text not null check (char_length(content) between 1 and 200),
  created_at timestamptz not null default now()
);

create index if not exists room_messages_room_created_idx
  on public.room_messages(room_id, created_at desc);

alter table public.room_messages enable row level security;

drop policy if exists "members can read room messages" on public.room_messages;
create policy "members can read room messages"
on public.room_messages for select
to authenticated
using (public.is_room_member(room_id));

revoke all on public.room_messages from anon;
grant select on public.room_messages to authenticated;

create or replace function public.send_room_message(
  p_room_id uuid,
  p_content text,
  p_kind text default 'text'
)
returns public.room_messages
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_nickname text;
  v_content text;
  v_kind text := coalesce(p_kind, 'text');
  v_message public.room_messages;
begin
  if v_uid is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select nickname into v_nickname
  from public.room_players
  where room_id = p_room_id and user_id = v_uid;

  if v_nickname is null then
    raise exception 'ROOM_MEMBERSHIP_REQUIRED';
  end if;

  if not exists (
    select 1
    from public.rooms
    where id = p_room_id
      and status <> 'closed'
      and expires_at > now()
  ) then
    raise exception 'ROOM_EXPIRED';
  end if;

  v_content := btrim(coalesce(p_content, ''));
  if char_length(v_content) < 1
    or char_length(v_content) > 200
    or v_kind not in ('text', 'emoji') then
    raise exception 'INVALID_MESSAGE';
  end if;

  if (
    select count(*)
    from public.room_messages
    where room_id = p_room_id
      and user_id = v_uid
      and created_at > now() - interval '6 seconds'
  ) >= 8 then
    raise exception 'ROOM_RATE_LIMITED';
  end if;

  insert into public.room_messages (room_id, user_id, nickname, kind, content)
  values (p_room_id, v_uid, v_nickname, v_kind, v_content)
  returning * into v_message;

  return v_message;
end;
$$;

revoke all on function public.send_room_message(uuid, text, text) from public;
grant execute on function public.send_room_message(uuid, text, text) to authenticated;

-- Scoring: a correct filled cell is +10, an incorrect value is -4.
-- Notes and clearing a cell do not affect the score.
create or replace function public.apply_room_changes(
  p_room_id uuid,
  p_changes jsonb,
  p_expected_version integer
)
returns public.rooms
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_room public.rooms;
  v_values smallint[];
  v_notes smallint[];
  v_owners text[];
  v_change jsonb;
  v_cell integer;
  v_value integer;
  v_cell_notes integer;
  v_previous_value integer;
  v_givens text;
  v_solution text;
  v_board text;
  v_won boolean := false;
  v_score_delta integer := 0;
  v_correct_delta integer := 0;
  v_mistake_delta integer := 0;
begin
  if v_uid is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select * into v_room
  from public.rooms
  where id = p_room_id
  for update;

  if not found then
    raise exception 'ROOM_NOT_FOUND';
  end if;
  if not public.is_room_member(p_room_id) then
    raise exception 'ROOM_MEMBERSHIP_REQUIRED';
  end if;
  if v_room.status <> 'playing' or v_room.expires_at <= now() then
    raise exception 'ROOM_NOT_PLAYING';
  end if;
  if p_expected_version <> v_room.version then
    raise exception 'ROOM_VERSION_CONFLICT';
  end if;
  if jsonb_typeof(p_changes) <> 'array'
    or jsonb_array_length(p_changes) < 1
    or jsonb_array_length(p_changes) > 81 then
    raise exception 'INVALID_CHANGES';
  end if;

  v_values := v_room.values;
  v_notes := v_room.notes;
  v_owners := v_room.owners;
  v_givens := v_room.puzzle_data ->> 'givens';
  v_solution := v_room.puzzle_data ->> 'solution';

  for v_change in select value from jsonb_array_elements(p_changes)
  loop
    if jsonb_typeof(v_change) <> 'object'
      or not (v_change ? 'i')
      or not (v_change ? 'v')
      or not (v_change ? 'n') then
      raise exception 'INVALID_CHANGES';
    end if;

    v_cell := (v_change ->> 'i')::integer;
    v_value := (v_change ->> 'v')::integer;
    v_cell_notes := (v_change ->> 'n')::integer;

    if v_cell < 0 or v_cell > 80
      or v_value < 0 or v_value > 9
      or v_cell_notes < 0 or v_cell_notes > 511 then
      raise exception 'INVALID_CHANGES';
    end if;
    if substr(v_givens, v_cell + 1, 1) <> '0' then
      raise exception 'GIVEN_CELL';
    end if;
    if v_value <> 0 then
      v_cell_notes := 0;
    end if;

    v_previous_value := v_values[v_cell + 1];
    if v_value > 0 and v_value <> v_previous_value then
      if v_value::text = substr(v_solution, v_cell + 1, 1) then
        v_score_delta := v_score_delta + 10;
        v_correct_delta := v_correct_delta + 1;
      else
        v_score_delta := v_score_delta - 4;
        v_mistake_delta := v_mistake_delta + 1;
      end if;
    end if;

    v_values[v_cell + 1] := v_value::smallint;
    v_notes[v_cell + 1] := v_cell_notes::smallint;
    v_owners[v_cell + 1] := v_uid::text;
  end loop;

  if v_score_delta <> 0 then
    update public.room_players
    set score = greatest(0, score + v_score_delta),
        correct_moves = correct_moves + v_correct_delta,
        mistakes = mistakes + v_mistake_delta
    where room_id = p_room_id and user_id = v_uid;
  end if;

  select string_agg(v_values[cells.i]::text, '' order by cells.i)
  into v_board
  from generate_series(1, 81) as cells(i);
  v_won := v_board = v_solution;

  update public.rooms
  set values = v_values,
      notes = v_notes,
      owners = v_owners,
      version = version + 1,
      status = case when v_won then 'won' else status end,
      elapsed_ms = greatest(0, floor(extract(epoch from (now() - started_at)) * 1000)::bigint),
      finished_at = case when v_won then now() else null end,
      updated_at = now()
  where id = p_room_id
  returning * into v_room;

  return v_room;
end;
$$;

revoke all on function public.apply_room_changes(uuid, jsonb, integer) from public;
grant execute on function public.apply_room_changes(uuid, jsonb, integer) to authenticated;

create or replace function public.reset_room_scores_on_start()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.room_players
  set score = 0,
      correct_moves = 0,
      mistakes = 0,
      is_ready = true
  where room_id = new.id;
  return new;
end;
$$;

drop trigger if exists reset_room_scores_on_start on public.rooms;
create trigger reset_room_scores_on_start
after update of status, puzzle_data on public.rooms
for each row
when (
  new.status = 'playing'
  and (old.status is distinct from 'playing' or old.puzzle_data is distinct from new.puzzle_data)
)
execute function public.reset_room_scores_on_start();

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'room_messages'
  ) then
    execute 'alter publication supabase_realtime add table public.room_messages';
  end if;
end;
$$;
